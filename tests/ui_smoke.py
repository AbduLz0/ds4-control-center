    check('stick mode changes are saved', pg.evaluate("() => __mock.calls.some(c=>c[0]==='save_mapping'&&c[1].left_stick==='arrows')"))
    pg.screenshot(path=str(OUT / '15-mapping-enabled.png'), full_page=True)
    # --- settings
    pg.click('[data-page=settings]'); pg.click('#s-theme [data-t=aurora]'); pg.wait_for_timeout(400)
    check('theme applies instantly', pg.evaluate("() => document.body.dataset.theme") == 'aurora')
    check('theme persisted via bridge', pg.evaluate("() => __mock.calls.some(c=>c[0]==='save_settings'&&c[1].theme==='aurora')"))
    pg.screenshot(path=str(OUT / '08-settings-aurora.png'), full_page=True)
    # --- v0.3: battery history, light bar, alerts, auto profiles, report, shortcuts
    pg.evaluate("() => { __mock.battery={percent:73,status:'Discharging',charging:false,full:false}; }")
