    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 1360, 'height': 900})
    errors = []
    pg.on('pageerror', lambda e: errors.append(str(e))); pg.on('console', lambda m: m.type == 'error' and errors.append(m.text))
    pg.add_init_script(path=str(ROOT / 'tests/ui_mock.js'))
    pg.goto('file://' + str(ROOT / 'index.html')); pg.wait_for_timeout(500)
    # --- connected, idle
    check('stage not idle when connected', 'idle' not in pg.get_attribute('#stage', 'class'))
    check('connection chip shows Bluetooth', 'Bluetooth' in pg.inner_text('#ctl-chips'))
    check('battery shows 73%', pg.inner_text('#bat-pct') == '73%')
    # --- press buttons, move sticks, triggers, touch
    pg.evaluate("""() => { const m=__mock; m.down=['cross','l1','dpad-left','ps','l3']; m.axes={lx:.8,ly:-.5,rx:-.3,ry:.9,l2:.62,r2:1};
      m.touch=[{active:true,x:.3,y:.4},{active:true,x:.75,y:.7}]; m.counts={cross:3,circle:1}; m.log('button','Cross pressed'); m.log('system','Connected: Wireless Controller (Bluetooth)'); m.seq++; }""")
    pg.wait_for_timeout(400)
    on = pg.evaluate("() => [...document.querySelectorAll('#ctl-host [data-btn].on')].map(e=>e.dataset.btn).sort()")
    check('pressed buttons light up', on == sorted(['cross','l1','dpad-left','ps','l3','l2','r2']), on)
    cap = pg.get_attribute('#ctl-host [data-btn=l3] .cap', 'transform')
    check('left stick cap moved on the controller', cap and 'translate(13.6 -8.5)' in cap, cap)
    h = pg.evaluate("() => +document.querySelector('#ctl-host [data-fill=l2]').getAttribute('height')")
    check('L2 fill proportional to pressure (0.62*52=32)', h == 32, h)
    check('touch fingers visible', pg.evaluate("() => document.querySelectorAll('#ctl-host .finger.act').length") == 2)
    check('L2 label shows percentage', '62%' in pg.text_content('#ctl-host [data-tl=l2]'))
    check('event shown in recent input', 'Cross pressed' in pg.inner_text('#ov-events'))
    pg.screenshot(path=str(OUT / '01-dashboard-live.png'))
    # --- released
    pg.evaluate("() => { const m=__mock; m.down=[]; m.axes={lx:0,ly:0,rx:0,ry:0,l2:0,r2:0}; m.touch.forEach(t=>t.active=false); m.seq++; }"); pg.wait_for_timeout(300)
    check('buttons release', pg.evaluate("() => document.querySelectorAll('#ctl-host [data-btn].on').length") == 0)
    # --- disconnected + unavailable battery
    pg.evaluate("() => { __mock.connected=false; __mock.seq++; }"); pg.wait_for_timeout(1300)
    check('stage idle when disconnected', 'idle' in pg.get_attribute('#stage', 'class'))
    check('battery N/A (not zero) when disconnected', pg.inner_text('#bat-pct') == 'N/A')
    check('reconnect enabled / disconnect disabled', not pg.is_disabled('#btn-reconnect') and pg.is_disabled('#btn-disconnect'))
    pg.screenshot(path=str(OUT / '02-dashboard-disconnected.png'))
    pg.evaluate("() => { __mock.connected=true; __mock.battery=null; __mock.seq++; }"); pg.wait_for_timeout(1300)
    check('connected without battery data shows N/A', pg.inner_text('#bat-pct') == 'N/A' and 'not the same as 0%' in pg.inner_text('#bat-note'))
    pg.evaluate("() => { __mock.battery={percent:73,status:'Charging',charging:true,full:false}; }")
    # --- reconnect/disconnect actions reach the bridge
    pg.evaluate("() => { __mock.connected=true; __mock.seq++; }"); pg.wait_for_timeout(1200)
    pg.click('#btn-disconnect'); pg.wait_for_timeout(200)
    check('disconnect action calls bridge', pg.evaluate("() => __mock.calls.some(c=>c[0]==='disconnect')"))
    # --- diagnostics
    pg.click('[data-page=diagnostics]'); pg.wait_for_timeout(200)
    pg.evaluate("() => { const m=__mock; m.axes={lx:.4,ly:.3,rx:-.6,ry:.2,l2:.3,r2:0}; m.seq++; }"); pg.wait_for_timeout(500)
    check('stick readout in diagnostics', pg.inner_text('#dl-x') == '0.400' and pg.inner_text('#dl-r') == '50%', pg.inner_text('#dl-r'))
    check('outside dead zone flagged', 'Outside' in pg.inner_text('#dg-lchip'))
    pg.screenshot(path=str(OUT / '03-diag-sticks.png'))
