    check('chosen swatch highlighted', pg.evaluate("() => document.querySelector('#lb-swatches [data-lb=\"#ff1e1e\"]').classList.contains('on')"))
    pg.fill('#lb-color', '#00ff88'); pg.click('#lb-apply'); pg.wait_for_timeout(300)
