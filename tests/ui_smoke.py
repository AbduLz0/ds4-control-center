"""Headless UI check: loads the real frontend with a simulated bridge, drives it, and takes screenshots.
Usage: python tests/ui_smoke.py [outdir]"""
import sys, pathlib, json
from playwright.sync_api import sync_playwright

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '/tmp/shots'); OUT.mkdir(parents=True, exist_ok=True)
fails = []
def check(name, cond, detail=''):
    print(('PASS ' if cond else 'FAIL ') + name + (' ' + str(detail) if detail and not cond else ''))
    if not cond: fails.append(name)

