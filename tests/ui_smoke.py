    pg.screenshot(path=str(OUT / '14-mapping.png'), full_page=True)
    pg.click('[data-preset=racing]'); pg.wait_for_timeout(500)
    check('applying a preset reaches the bridge', pg.evaluate("() => __mock.calls.some(c=>c[0]==='apply_mapping_preset'&&c[1]==='racing')"))
    check('preset chip updates', 'Racing' in pg.inner_text('#map-preset-chip'), pg.inner_text('#map-preset-chip'))
    pg.locator('#map-enable').check(force=True); pg.wait_for_timeout(500)
    check('enabling key mapping reaches the bridge', pg.evaluate("() => __mock.calls.some(c=>c[0]==='set_mapping_enabled'&&c[1]===true)"))
    check('mapping chip says On', 'On' in pg.inner_text('#map-chip'), pg.inner_text('#map-chip'))
    pg.locator('[data-rebind=cross]').first.click(); pg.wait_for_timeout(150); pg.keyboard.press('g'); pg.wait_for_timeout(500)
    check('rebinding a button saves a new key', pg.evaluate("() => __mock.calls.some(c=>c[0]==='save_mapping'&&c[1].bindings&&c[1].bindings.cross==='KEY_G')"))
    pg.click('#map-help'); pg.wait_for_timeout(200)
    check('uinput help explains the one-time system change', pg.is_visible('#dlg-uinput') and 'enable-uinput' in pg.inner_text('#uinput-command'))
