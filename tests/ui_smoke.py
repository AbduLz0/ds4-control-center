    check('launch passes app id to bridge', pg.evaluate("() => __mock.calls.some(c=>c[0]==='launch_game'&&c[1]==='620')"))
    check('profile applied after launch (dead zone 12%)', 'dead zone 12%' in pg.inner_text('#profile-chip'))
    pg.click('#profile-chip'); check('profile chip clears', 'hidden' in pg.get_attribute('#profile-chip', 'class'))
    pg.click('.game:has-text("Hades") [data-game=launch]'); pg.wait_for_timeout(300)
    check('launching a Lutris game uses the universal API', pg.evaluate("() => __mock.calls.some(c=>c[0]==='launch_any_game'&&c[1]==='lutris:1')"))
    check('launching another game clears the stale manual profile', 'hidden' in pg.get_attribute('#profile-chip', 'class'))
    pg.screenshot(path=str(OUT / '07-gaming.png'), full_page=True)
    # --- virtual Xbox pad
    pg.locator('#vpad-enable').check(force=True); pg.wait_for_timeout(400)
    check('virtual pad toggle reaches the bridge', pg.evaluate("() => __mock.calls.some(c=>c[0]==='set_virtual_pad'&&c[1]===true)"))
