    check('moving stick aborts drift test', pg.inner_text('#drift-start') == 'Start drift test', pg.inner_text('#drift-start'))
    # circularity
    pg.click('#circ-toggle')
    pg.evaluate("""async () => { for (let i=0;i<72;i++){ const a=i/72*Math.PI*2; __mock.axes.lx=Math.cos(a)*0.97; __mock.axes.ly=Math.sin(a)*0.97; __mock.axes.rx=Math.cos(a)*0.9; __mock.axes.ry=Math.sin(a)*0.7; __mock.seq++; await new Promise(r=>setTimeout(r,70)); } }""")
    pg.wait_for_timeout(300)
    check('circularity coverage high after full rotation', int(pg.inner_text('#cl-cov').rstrip('%')) >= 85, pg.inner_text('#cl-cov'))
    check('elliptical right stick has lower roundness than left', int(pg.inner_text('#cr-round').rstrip('%')) < int(pg.inner_text('#cl-round').rstrip('%')), (pg.inner_text('#cl-round'), pg.inner_text('#cr-round')))
    pg.screenshot(path=str(OUT / '04-diag-circularity.png'), full_page=True)
    # buttons tab
    pg.click('[data-dtab=buttons]'); pg.evaluate("() => { __mock.axes={lx:0,ly:0,rx:0,ry:0,l2:.75,r2:0}; __mock.down=['circle']; __mock.counts={cross:3,circle:2,l1:1}; __mock.seq++; }"); pg.wait_for_timeout(500)
